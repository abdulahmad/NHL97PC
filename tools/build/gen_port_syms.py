#!/usr/bin/env python3
"""gen_port_syms.py - write port/game_syms.h: the addresses of the game labels the SDL2 port uses, by name.

  python3 tools/build/gen_port_syms.py [--port port] [--obj build/obj] [--obj11 build/v11/obj] [--check]

The port (branch cursor/overbar-96pc-6801, folder port/) loads the retail HOCKEY.EXE and reaches into it by address.
Its C files write those addresses as SYM_<label>, where <label> is a label of this source tree (SYM_PlayGame,
SYM_tickcount, SYM_GameLoop_menucall). This tool collects every SYM_ token of port/*.c and port/*.h, looks each
label up in the objects of the last ./build.sh (section s_<ADDR> + symbol value, as update_symbols.py does) and
writes port/game_syms.h with one #define per label, in address order. Run it after a rename (rename_symbol.py does
not see port/): a SYM_ token whose label no longer exists is an error that names the files using it, so a renamed
label cannot leave a stale number behind.
--check: write nothing; exit 1 if port/game_syms.h is not what would be written.
Without a port/ folder (main, fable-work) there is nothing to do."""
import os, re, sys, argparse
HERE = os.path.dirname(os.path.abspath(__file__))
_td = HERE
while os.path.basename(_td) != 'tools' and _td != os.path.dirname(_td):
    _td = os.path.dirname(_td)
if _td not in sys.path:
    sys.path.insert(0, _td)
import paths
ROOT = paths.ROOT
from link_src import read_elf, read_layout
OUT = 'game_syms.h'
HEAD = ('/* Addresses of the HOCKEY.EXE labels the port uses (generated by tools/build/gen_port_syms.py; do not edit).\n'
        ' * SYM_<label> is the linear address of <label> in the source tree (src/). Use SYM_<label> in the port, not a number:\n'
        ' * add the token, run the tool after ./build.sh and ./build.sh 11, and the #define appears here.\n'
        ' * Each one holds the address in patch 1.1 and in retail 1.0; le_load.c sets game_v11 from the EXE it loads. */\n'
        '#ifndef GAME_SYMS_H\n#define GAME_SYMS_H\n\nextern int game_v11;\n\n')


def all_labels(objdir, layout=None):
    """label -> (address, source file) for every label of the tree, exported or not. layout: src/segments_v11.txt
    for the patch 1.1 objects (each file keeps its 1.0 section name s_<1.0 start>)"""
    out = {}
    segs10 = read_layout()
    segs = read_layout(layout) if layout else segs10
    for sg, s10 in zip(segs, segs10):
        d, secs, syms, rels = read_elf(os.path.join(objdir, os.path.splitext(sg['src'])[0] + '.o'))
        si = next(i for i, s in enumerate(secs) if s['name'] == 's_%05X' % s10['start'])
        for sy in syms:
            if sy['shndx'] == si and sy['name'] and not sy['name'].startswith('s_'):
                out[sy['name']] = (sg['start'] + sy['value'], sg['src'])
    return out


def used(port):
    """SYM_ label -> sorted port files that use it"""
    u = {}
    for f in sorted(os.listdir(port)):
        if f == OUT or not f.endswith(('.c', '.h')): continue
        for n in re.findall(r'\bSYM_([A-Za-z_][A-Za-z0-9_]*)', open(os.path.join(port, f), errors='replace').read()):
            u.setdefault(n, set()).add(f)
    return {n: sorted(v) for n, v in u.items()}


def render(port, objdir, obj11):
    lab = all_labels(objdir); u = used(port)
    lab11 = all_labels(obj11, os.path.join(ROOT, 'src/segments_v11.txt'))
    bad = sorted(n for n in u if n not in lab)
    for n in bad: print('no label %s in src/ (used as SYM_%s in %s)' % (n, n, ', '.join(u[n])), file=sys.stderr)
    bad11 = sorted(n for n in u if n in lab and n not in lab11)
    for n in bad11: print('no label %s in the patch 1.1 build (used as SYM_%s in %s)' % (n, n, ', '.join(u[n])), file=sys.stderr)
    if bad or bad11: sys.exit(1)
    w = max([len(n) for n in u] + [1])
    out = [HEAD]
    for n in sorted(u, key=lambda n: (lab[n][0], n)):
        out.append('#define SYM_%-*s (game_v11 ? 0x%05Xu : 0x%05Xu)   /* %s */\n' % (w, n, lab11[n][0], lab[n][0], lab[n][1]))
    out.append('\n#endif\n')
    return ''.join(out), len(u)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--port', default=os.path.join(ROOT, 'port')); ap.add_argument('--obj', default=os.path.join(ROOT, 'build/obj'))
    ap.add_argument('--obj11', default=os.path.join(ROOT, 'build/v11/obj'))
    ap.add_argument('--check', action='store_true')
    a = ap.parse_args()
    if not os.path.isdir(a.port): print('no port/ folder here: nothing to do'); return
    new, n = render(a.port, a.obj, a.obj11)
    p = os.path.join(a.port, OUT)
    old = open(p).read() if os.path.exists(p) else ''
    if a.check:
        print('port/%s up to date' % OUT if new == old else 'port/%s is stale: run tools/build/gen_port_syms.py' % OUT); sys.exit(0 if new == old else 1)
    if new != old: open(p, 'w').write(new)
    print('wrote port/%s (%d labels)%s' % (OUT, n, '' if new != old else ', unchanged'))


if __name__ == '__main__':
    main()
